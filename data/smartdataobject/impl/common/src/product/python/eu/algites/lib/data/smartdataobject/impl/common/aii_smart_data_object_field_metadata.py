"""Common format-independent metadata contract for one effective SDO field."""
from __future__ import annotations
from typing import Protocol, Any

class AIiSmartDataObjectFieldMetadata(Protocol):
    """A field's semantic identity, canonical data name, type and annotation."""
    def getSemanticFieldName(self) -> str: ...
    def getDataFieldName(self) -> str: ...
    def getEffectiveGetter(self) -> Any: ...
    def getEffectiveReturnType(self) -> Any: ...
    def getDefinition(self) -> Any: ...
