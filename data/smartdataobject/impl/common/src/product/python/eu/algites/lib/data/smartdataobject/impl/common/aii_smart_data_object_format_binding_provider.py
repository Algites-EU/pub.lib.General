"""Extensible metadata and codec service-provider contract."""
from __future__ import annotations
from typing import Protocol

class AIiSmartDataObjectFormatBindingProvider(Protocol):
    """Discoverable service providing one binding interpretation of a format."""
    def getFormatId(self) -> str: ...
    def getProviderId(self) -> str: ...
    def resolveMetadata(self, aMetadata: object) -> object | None: ...
    def createMarshaller(self) -> object: ...
    def createUnmarshaller(self) -> object: ...
