"""Format-neutral metadata contract for a concrete SDO implementation."""
from __future__ import annotations
from typing import Protocol
from .aii_smart_data_object_field_metadata import AIiSmartDataObjectFieldMetadata

class AIiSmartDataObjectMetadata(Protocol):
    """Class metadata with optional format-provider contributions."""
    def getImplementationClass(self) -> type: ...
    def getFields(self) -> tuple[AIiSmartDataObjectFieldMetadata, ...]: ...
    def getField(self, aSemanticFieldName: str) -> AIiSmartDataObjectFieldMetadata | None: ...
    def getFormatBindings(self) -> tuple[object, ...]: ...
    def getFormatBinding(self, aFormatId: str, aProviderId: str) -> object | None: ...
