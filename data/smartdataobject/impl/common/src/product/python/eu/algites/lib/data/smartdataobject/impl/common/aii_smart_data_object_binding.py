"""A purpose-scoped binding for one concrete SDO implementation."""
from __future__ import annotations
from typing import Protocol

class AIiSmartDataObjectFieldBinding(Protocol):
    """An optionally explicitly chosen nested SDO implementation."""
    def getFieldMetadata(self) -> object: ...
    def getImplementationClassOverride(self) -> type | None: ...

class AIiSmartDataObjectBinding(Protocol):
    """Read-only contracts and SDO-valued field bindings for one class."""
    def getImplementationClass(self) -> type: ...
    def getMetadata(self) -> object: ...
    def getDeclaredReadContracts(self) -> frozenset[type]: ...
    def getEffectiveReadContracts(self) -> frozenset[type]: ...
    def getFieldBindings(self) -> tuple[AIiSmartDataObjectFieldBinding, ...]: ...
    def getFieldBinding(self, aSemanticFieldName: str) -> AIiSmartDataObjectFieldBinding | None: ...
