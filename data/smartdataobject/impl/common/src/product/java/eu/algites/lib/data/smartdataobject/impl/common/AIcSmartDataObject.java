package eu.algites.lib.data.smartdataobject.impl.common;

import eu.algites.lib.data.dataobject.AIaDataObjectField;
import eu.algites.lib.data.dataobject.AInDataObjectFieldDefaultKind;
import eu.algites.lib.data.dataobject.AInFieldPresenceKind;
import eu.algites.lib.data.smartdataobject.AIcdSmartDataValidationIssue;
import eu.algites.lib.data.smartdataobject.AIiSmartDataObject;
import eu.algites.lib.data.smartdataobject.AIidVirtualFieldValue;
import eu.algites.lib.data.smartdataobject.AInSdoFieldValueLoadingMode;
import eu.algites.lib.text.format.AIiTextFormatProfile;
import eu.algites.lib.text.format.AInTextOutputObjectReferenceMode;
import java.lang.reflect.Array;
import java.math.BigDecimal;
import java.util.ArrayList;
import java.util.Collections;
import java.util.IdentityHashMap;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import java.util.Set;
import java.util.regex.Pattern;

/**
 * New format-independent mutable SmartDataObject foundation. It does not use,
 * extend or delegate to the deprecated runtime in {@code impl.standard}.
 * Metadata are obtained only from {@link AIsSmartDataObjectMetadataRegistry}.
 * Instances have no reference to binding registries or format providers.
 *
 * <p>All getters/setters generated by SDO Codegen use semantic field names.
 * Absence, explicit null, and the explicit empty marker remain distinct.
 *
 * @author linhart1
 */
public abstract class AIcSmartDataObject implements AIiSmartDataObject {
    private static final Object EMPTY = new Object();
    private final Map<String, Object> values = new LinkedHashMap<>();

    /** Initializes a new, empty SDO. */
    protected AIcSmartDataObject() { }

    /**
     * Initializes an SDO from a typed virtual graph.
     * @param aMapping semantic field names and values; may be null for an empty object
     */
    protected AIcSmartDataObject(Map<String, AIidVirtualFieldValue> aMapping) {
        if (aMapping != null) aMapping.forEach((name, value) ->
                set_RawField(name, value == null ? null : value.getValueRepresentation()));
    }

    /**
     * Returns this object's immutable snapshot of explicitly stored semantic values.
     * Explicit null remains an entry; the technical empty sentinel is rendered as an empty string.
     * @return copy of stored semantic field values
     */
    public final Map<String, Object> getRawValues() {
        Map<String, Object> result = new LinkedHashMap<>();
        values.forEach((name, value) -> result.put(name, value == EMPTY ? "" : value));
        return Collections.unmodifiableMap(result);
    }

    /**
     * Checks raw presence independently of explicit null.
     * @param aSemanticFieldName field's semantic identity
     * @return whether the field has been explicitly assigned
     */
    public final boolean isRawFieldPresent(String aSemanticFieldName) {
        requireField(aSemanticFieldName);
        return values.containsKey(aSemanticFieldName);
    }

    /**
     * Retrieves a raw value, returning null for an absent or explicitly null value.
     * Use {@link #isRawFieldPresent(String)} to distinguish absence.
     * @param aSemanticFieldName semantic field name
     * @return raw value or null; technical empty marker is returned as an empty string
     */
    public final Object getRawValue(String aSemanticFieldName) {
        return get_RawField(aSemanticFieldName);
    }

    /**
     * Assigns a value through the common metadata-driven validation path.
     * Intended for typed generated setters and the common object factory.
     * @param aSemanticFieldName semantic field name
     * @param aValue assigned value, including explicit null
     * @throws IllegalArgumentException when the field or value is invalid
     */
    protected final void set_RawField(String aSemanticFieldName, Object aValue) {
        AIiSmartDataObjectFieldMetadata field = requireField(aSemanticFieldName);
        if (field.getDefinition().presence() == AInFieldPresenceKind.FORBIDDEN)
            throw new IllegalArgumentException("Forbidden field: " + aSemanticFieldName);
        if (aValue == null && !field.getDefinition().allowsNull())
            throw new IllegalArgumentException("Null is not allowed: " + aSemanticFieldName);
        if (aValue != null && !boxed(field.getEffectiveGetter().getReturnType()).isInstance(aValue))
            throw new IllegalArgumentException("Wrong field type for " + aSemanticFieldName + ": " + aValue.getClass());
        validateValue(field, aValue);
        values.put(aSemanticFieldName, aValue);
    }

    /**
     * Reads the raw value without evaluating defaults.
     * @param aSemanticFieldName semantic field name
     * @return raw value or null
     */
    protected final Object get_RawField(String aSemanticFieldName) {
        requireField(aSemanticFieldName);
        Object value = values.get(aSemanticFieldName);
        return value == EMPTY ? "" : value;
    }

    /**
     * Reads the effective value, substituting declared defaults only where allowed.
     * Does not change the raw field store.
     * @param aSemanticFieldName semantic field name
     * @return effective value or null
     */
    protected final Object get_EffectiveField(String aSemanticFieldName) {
        AIiSmartDataObjectFieldMetadata field = requireField(aSemanticFieldName);
        AIaDataObjectField definition = field.getDefinition();
        if (definition.presence() == AInFieldPresenceKind.FORBIDDEN)
            throw new IllegalStateException("Forbidden field: " + aSemanticFieldName);
        boolean present = values.containsKey(aSemanticFieldName);
        Object raw = values.get(aSemanticFieldName);
        if (present && raw != EMPTY) return raw;
        AInDataObjectFieldDefaultKind kind = definition.defaultValue().kind();
        if (definition.defaultValue().defined() &&
                ((!present && kind == AInDataObjectFieldDefaultKind.IF_FIELD_VALUE_NOT_PRESENT) ||
                 (present && raw == EMPTY && kind == AInDataObjectFieldDefaultKind.IF_FIELD_VALUE_EMPTY)))
            return parseDefault(field);
        return present && raw == EMPTY ? "" : null;
    }

    /**
     * Assigns the explicit EMPTY sentinel, which is distinct from {@code setXxx("")}.
     * @param aSemanticFieldName semantic field name
     */
    protected final void set_EmptyField(String aSemanticFieldName) {
        AIiSmartDataObjectFieldMetadata field = requireField(aSemanticFieldName);
        if (!field.getDefinition().isEmptyAllowed()) throw new IllegalArgumentException("EMPTY forbidden: " + aSemanticFieldName);
        values.put(aSemanticFieldName, EMPTY);
    }

    /** @param aSemanticFieldName semantic field name @return explicit empty sentinel status */
    protected final boolean isEmpty_Field(String aSemanticFieldName) {
        requireField(aSemanticFieldName);
        return values.get(aSemanticFieldName) == EMPTY;
    }

    /** @param aSemanticFieldName semantic field name @return raw presence */
    protected final boolean isPresent_Field(String aSemanticFieldName) {
        return isRawFieldPresent(aSemanticFieldName);
    }

    /** @param aSemanticFieldName semantic field name to clear */
    protected final void unset_Field(String aSemanticFieldName) {
        requireField(aSemanticFieldName);
        values.remove(aSemanticFieldName);
    }

    /**
     * Creates a writable list or indexed list once and keeps the same attached instance.
     * @param aSemanticFieldName collection field
     * @param aMapped true when a multi-mapped list is required
     * @return previously assigned or new collection
     */
    protected final Object get_OrCreateCollectionField(String aSemanticFieldName, boolean aMapped) {
        requireField(aSemanticFieldName);
        if (values.containsKey(aSemanticFieldName)) return get_RawField(aSemanticFieldName);
        Object result = aMapped ? new eu.algites.lib.common.list.AIcMultiMappedList<>() : new ArrayList<>();
        set_RawField(aSemanticFieldName, result);
        return result;
    }

    /**
     * Creates and attaches a nominal indexed collection with generated factory semantics.
     * @param aSemanticFieldName indexed field name
     * @param aFactory indexed collection factory
     * @param <V> indexed element type
     * @param <T> concrete indexed collection type
     * @return attached collection
     */
    @SuppressWarnings("unchecked")
    protected final <V, T extends eu.algites.lib.common.list.AIiMultiMappedList<V>> T
            get_OrCreateNamedMappedCollectionField(String aSemanticFieldName,
            java.util.function.Function<java.util.Collection<? extends eu.algites.lib.common.list.AIiKeyDefinition<V, ?>>, T> aFactory) {
        Objects.requireNonNull(aFactory, "aFactory");
        if (values.containsKey(aSemanticFieldName)) return (T) get_RawField(aSemanticFieldName);
        T result = aFactory.apply(List.of());
        set_RawField(aSemanticFieldName, result);
        return result;
    }

    /**
     * Attaches one decoded value without invoking generated setters.
     * @param aSemanticFieldName existing semantic field
     * @param aValue decoded value
     */
    final void populateField(String aSemanticFieldName, Object aValue) {
        set_RawField(aSemanticFieldName, aValue);
    }

    private AIiSmartDataObjectFieldMetadata requireField(String aSemanticFieldName) {
        Objects.requireNonNull(aSemanticFieldName, "aSemanticFieldName");
        AIiSmartDataObjectFieldMetadata field = AIsSmartDataObjectMetadataRegistry.forType(getClass())
                .getField(aSemanticFieldName);
        if (field == null) throw new IllegalArgumentException("Unknown semantic SDO field: " + aSemanticFieldName);
        return field;
    }

    private static Class<?> boxed(Class<?> type) {
        if (!type.isPrimitive()) return type;
        if (type == int.class) return Integer.class;
        if (type == long.class) return Long.class;
        if (type == double.class) return Double.class;
        if (type == float.class) return Float.class;
        if (type == short.class) return Short.class;
        if (type == byte.class) return Byte.class;
        if (type == boolean.class) return Boolean.class;
        if (type == char.class) return Character.class;
        return type;
    }

    private static Object parseDefault(AIiSmartDataObjectFieldMetadata field) {
        String value = field.getDefinition().defaultValue().value();
        Class<?> type = boxed(field.getEffectiveGetter().getReturnType());
        if (type == String.class) return value;
        if (type == Integer.class) return Integer.valueOf(value);
        if (type == Long.class) return Long.valueOf(value);
        if (type == Short.class) return Short.valueOf(value);
        if (type == Double.class) return Double.valueOf(value);
        if (type == Float.class) return Float.valueOf(value);
        if (type == BigDecimal.class) return new BigDecimal(value);
        if (type == Boolean.class) return Boolean.valueOf(value);
        if (type.isEnum()) {
            for (Object constant : type.getEnumConstants()) {
                if (constant instanceof eu.algites.lib.common.enums.AIiEnumItem<?> item
                        && value.equals(String.valueOf(item.code()))) return constant;
                // Persistent enum values are resolved solely by stable AIiEnumItem.code().
            }
        }
        throw new IllegalArgumentException("Unsupported default value type " + type + " for " + field.getSemanticFieldName());
    }

    private static void validateValue(AIiSmartDataObjectFieldMetadata field, Object value) {
        if (value == null) return;
        AIaDataObjectField definition = field.getDefinition();
        if (definition.defaultValue().defined() &&
                definition.defaultValue().kind() == AInDataObjectFieldDefaultKind.CONSTRAINT_DEFAULT) {
            if (!Objects.equals(value, parseDefault(field)))
                throw new IllegalArgumentException("FIXED constraint violated: " + field.getSemanticFieldName());
        }
        var string = field.getStringConstraints();
        if (value instanceof String text && string != null) {
            int length = text.codePointCount(0, text.length());
            if (string.minLength() >= 0 && length < string.minLength() ||
                string.maxLength() >= 0 && length > string.maxLength() ||
                !string.pattern().isEmpty() && !Pattern.compile(string.pattern()).matcher(text).matches())
                throw new IllegalArgumentException("String constraint violated: " + field.getSemanticFieldName());
        }
        var numeric = field.getNumericConstraints();
        if (value instanceof Number number && numeric != null) {
            BigDecimal n = new BigDecimal(number.toString());
            if (!numeric.minimum().isEmpty()) {
                int cmp = n.compareTo(new BigDecimal(numeric.minimum()));
                if (cmp < 0 || cmp == 0 && numeric.exclusiveMinimum())
                    throw new IllegalArgumentException("Minimum constraint violated: " + field.getSemanticFieldName());
            }
            if (!numeric.maximum().isEmpty()) {
                int cmp = n.compareTo(new BigDecimal(numeric.maximum()));
                if (cmp > 0 || cmp == 0 && numeric.exclusiveMaximum())
                    throw new IllegalArgumentException("Maximum constraint violated: " + field.getSemanticFieldName());
            }
            if (!numeric.multipleOf().isEmpty() && n.remainder(new BigDecimal(numeric.multipleOf())).signum() != 0)
                throw new IllegalArgumentException("MultipleOf constraint violated: " + field.getSemanticFieldName());
        }
        var list = field.getListConstraints();
        if (value instanceof java.util.Collection<?> collection && list != null) {
            if (list.minItems() >= 0 && collection.size() < list.minItems() ||
                list.maxItems() >= 0 && collection.size() > list.maxItems() ||
                list.uniqueItems() && new LinkedHashSet<>(collection).size() != collection.size())
                throw new IllegalArgumentException("Collection constraint violated: " + field.getSemanticFieldName());
        }
        var object = field.getObjectConstraints();
        if (value instanceof Map<?, ?> map && object != null) {
            if (object.minProperties() >= 0 && map.size() < object.minProperties() ||
                object.maxProperties() >= 0 && map.size() > object.maxProperties())
                throw new IllegalArgumentException("Map constraint violated: " + field.getSemanticFieldName());
        }
    }

    private Map<String, Object> snapshot(boolean effective) {
        Map<String, Object> result = new LinkedHashMap<>();
        for (AIiSmartDataObjectFieldMetadata field :
                AIsSmartDataObjectMetadataRegistry.forType(getClass()).getFields()) {
            String name = field.getSemanticFieldName();
            if (values.containsKey(name) || effective && hasEffectiveDefault(field))
                result.put(name, effective ? get_EffectiveField(name) : get_RawField(name));
        }
        return result;
    }

    private boolean hasEffectiveDefault(AIiSmartDataObjectFieldMetadata field) {
        return field.getDefinition().defaultValue().defined() &&
                field.getDefinition().defaultValue().kind() == AInDataObjectFieldDefaultKind.IF_FIELD_VALUE_NOT_PRESENT;
    }

    /** {@inheritDoc} */
    @Override public final Set<String> get_RawNotPresentRequiredFields() { return missing(false); }
    /** {@inheritDoc} */
    @Override public final Set<String> get_EffectiveNotPresentRequiredFields() { return missing(true); }
    private Set<String> missing(boolean effective) {
        Set<String> result = new LinkedHashSet<>();
        for (AIiSmartDataObjectFieldMetadata field : AIsSmartDataObjectMetadataRegistry.forType(getClass()).getFields()) {
            String name = field.getSemanticFieldName();
            if (field.getDefinition().presence() == AInFieldPresenceKind.REQUIRED &&
                    !values.containsKey(name) && !(effective && hasEffectiveDefault(field))) result.add(name);
        }
        return Collections.unmodifiableSet(result);
    }

    /** {@inheritDoc} */
    @Override public final List<AIcdSmartDataValidationIssue> _getValidationIssues(AInSdoFieldValueLoadingMode aMode) {
        Objects.requireNonNull(aMode, "aMode");
        boolean effective = aMode == AInSdoFieldValueLoadingMode.EFFECTIVE_VALUES;
        List<AIcdSmartDataValidationIssue> result = new ArrayList<>();
        for (String missing : missing(effective)) result.add(new AIcdSmartDataValidationIssue(
                missing, "REQUIRED_ABSENT", "Required field is not present"));
        for (AIiSmartDataObjectFieldMetadata field : AIsSmartDataObjectMetadataRegistry.forType(getClass()).getFields()) {
            String name = field.getSemanticFieldName();
            if (values.containsKey(name)) {
                Object value = effective ? get_EffectiveField(name) : get_RawField(name);
                try { if (value == null && !field.getDefinition().allowsNull())
                    throw new IllegalArgumentException("Null forbidden"); validateValue(field, value); }
                catch (IllegalArgumentException error) {
                    result.add(new AIcdSmartDataValidationIssue(name, "FIELD_CONSTRAINT", error.getMessage()));
                }
            }
        }
        return List.copyOf(result);
    }

    private List<AIcdSmartDataValidationIssue> deepIssues(boolean effective) {
        List<AIcdSmartDataValidationIssue> result = new ArrayList<>();
        collectIssues(this, effective, "", new IdentityHashMap<>(), result);
        return List.copyOf(result);
    }
    private static void collectIssues(Object node, boolean effective, String path,
            IdentityHashMap<Object, Boolean> seen, List<AIcdSmartDataValidationIssue> result) {
        if (node == null || seen.put(node, Boolean.TRUE) != null) return;
        if (node instanceof AIcSmartDataObject sdo) {
            for (AIcdSmartDataValidationIssue issue : sdo._getValidationIssues(effective
                    ? AInSdoFieldValueLoadingMode.EFFECTIVE_VALUES : AInSdoFieldValueLoadingMode.RAW_VALUES))
                result.add(new AIcdSmartDataValidationIssue(path + issue.path(), issue.code(), issue.message()));
            sdo.snapshot(effective).forEach((field, child) -> collectIssues(child, effective,
                    path + field + ".", seen, result));
        } else if (node instanceof Iterable<?> items) {
            int i = 0;
            for (Object child : items) collectIssues(child, effective, path + "[" + i++ + "].", seen, result);
        } else if (node instanceof Map<?, ?> map) {
            map.forEach((key, child) -> collectIssues(child, effective, path + String.valueOf(key) + ".", seen, result));
        } else if (node.getClass().isArray()) {
            for (int i = 0; i < Array.getLength(node); i++)
                collectIssues(Array.get(node, i), effective, path + "[" + i + "].", seen, result);
        }
    }

    /** {@inheritDoc} */
    @Override public final List<AIcdSmartDataValidationIssue> get_DeeplyRawValuesValidationIssues() { return deepIssues(false); }
    /** {@inheritDoc} */
    @Override public final List<AIcdSmartDataValidationIssue> get_DeeplyEffectiveValuesValidationIssues() { return deepIssues(true); }
    /** {@inheritDoc} */
    @Override public final boolean is_ByRawValuesValid() { return _getValidationIssues(AInSdoFieldValueLoadingMode.RAW_VALUES).isEmpty(); }
    /** {@inheritDoc} */
    @Override public final boolean is_ByEffectiveValuesValid() { return _getValidationIssues(AInSdoFieldValueLoadingMode.EFFECTIVE_VALUES).isEmpty(); }
    /** {@inheritDoc} */
    @Override public final boolean is_DeeplyByRawValuesValid() { return deepIssues(false).isEmpty(); }
    /** {@inheritDoc} */
    @Override public final boolean is_DeeplyByEffectiveValuesValid() { return deepIssues(true).isEmpty(); }
    /** {@inheritDoc} */
    @Override public final Set<String> get_DeeplyRawNotPresentRequiredFields() { return deepMissing(false); }
    /** {@inheritDoc} */
    @Override public final Set<String> get_DeeplyEffectiveNotPresentRequiredFields() { return deepMissing(true); }
    private Set<String> deepMissing(boolean effective) {
        Set<String> result = new LinkedHashSet<>();
        for (AIcdSmartDataValidationIssue issue : deepIssues(effective))
            if ("REQUIRED_ABSENT".equals(issue.code())) result.add(issue.path());
        return Collections.unmodifiableSet(result);
    }

    /** {@inheritDoc} */
    @Override public final Map<String, AIidVirtualFieldValue> _toMapping(AInSdoFieldValueLoadingMode aMode) {
        Objects.requireNonNull(aMode, "aMode");
        Map<String, AIidVirtualFieldValue> result = new LinkedHashMap<>();
        snapshot(aMode == AInSdoFieldValueLoadingMode.EFFECTIVE_VALUES).forEach((name, value) ->
                result.put(name, new VirtualValue(value)));
        return Collections.unmodifiableMap(result);
    }
    private record VirtualValue(Object value) implements AIidVirtualFieldValue {
        @Override public Object getValueRepresentation() { return value; }
        @Override public Class<?> getValueClass() { return value == null ? Void.class : value.getClass(); }
    }

    /** {@inheritDoc} */
    @Override public final String toString_RawValues(AIiTextFormatProfile aProfile, AInTextOutputObjectReferenceMode aMode) {
        return render(aProfile, aMode, false);
    }
    /** {@inheritDoc} */
    @Override public final String toString_EffectiveValues(AIiTextFormatProfile aProfile, AInTextOutputObjectReferenceMode aMode) {
        return render(aProfile, aMode, true);
    }
    private String render(AIiTextFormatProfile profile, AInTextOutputObjectReferenceMode mode, boolean effective) {
        Objects.requireNonNull(profile, "profile");
        Objects.requireNonNull(mode, "mode");
        String formatId = profile.getFormatType().code();
        var providers = AIsSmartDataObjectFormatBindingProviderRegistry.getProviders(formatId);
        if (providers.size() != 1) throw new IllegalStateException("Exactly one format provider required for " + formatId
                + ", found " + providers.size());
        return providers.get(0).createMarshaller().marshal(this,
                AIcSmartDataObjectBindingRegistry.builder().register(getClass()).build());
    }
}
