#!/usr/bin/env python3
"""Promote generated canonical bootstrap contracts to persistent *.extgen roots.

The output is source-generated (and committed), never edited by hand. During the
initial compiler bootstrap it is independent of the disposable *.gen roots.
The temporary pub.tool.General bootstrap invokes --refresh automatically after a
successful complete build; --prune-seed removes historical extra paths without
checking old hashes at the start.
--refresh-defs updates only read-only contracts while preserving the independent
SDO seed, to break a bootstrap cycle. --check validates schema provenance,
source roles and hashes without requiring disposable generated sources.
"""
from __future__ import annotations

import argparse
import os
import uuid
import hashlib
import json
from pathlib import Path
import re
import shutil

from importlib.machinery import SourceFileLoader

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'generators/code/defscodegen/intf/src/product'
IMPLEMENTATION = ROOT / 'generators/code/defscodegen/impl/src/product'
# Keep the same API/implementation ownership for both technologies. The SDO
# inputs are read-only contracts generated by the independent Defs Codegen.
# SDO generator outputs are always independent of Defs generator outputs.
OUTPUTS = (
    ('java', SOURCE / 'java.gen', SOURCE / 'java.extgen'),
    ('python', SOURCE / 'python.gen', SOURCE / 'python.extgen'),
    ('java', IMPLEMENTATION / 'java.gen', IMPLEMENTATION / 'java.extgen'),
    ('python', IMPLEMENTATION / 'python.gen', IMPLEMENTATION / 'python.extgen'),
)
OLD_PACKAGE = 'eu.algites.tool.codegen.defs.model'
NEW_PACKAGE = 'eu.algites.tool.codegen.defs.bootstrap.model'
OLD_PATH = Path(*OLD_PACKAGE.split('.'))
NEW_PATH = Path(*NEW_PACKAGE.split('.'))
SCHEMA = SOURCE / 'jsondefs/eu/algites/tool/codegen/defs/model/canonical-model_1.jsondef.schema.json'
MANIFEST = ROOT / 'generators/code/defscodegen/intf/canonical-bootstrap-extgen.json'
NORMALIZE = SourceFileLoader('canonical_bootstrap_normalize', str(Path(__file__).with_name('normalize-canonical-bootstrap.py'))).load_module().normalize


def digest(data: bytes) -> str:
    """Return a stable content hash of generated bytes."""
    return hashlib.sha256(data).hexdigest()


def relocate(text: str, language: str) -> str:
    """Relocate import/package identifiers without changing canonical schema IDs."""
    if language == 'java':
        # Both read-only contracts and independent writable SDO output use the
        # same model package root, optionally followed by .impl(.intf).
        text, count = re.subn(r'(?m)^(package\s+)' + re.escape(OLD_PACKAGE)
                              + r'(?=\.impl(?:\.intf)?;|;)',
                              lambda m: m.group(1) + NEW_PACKAGE, text)
        if count != 1:
            raise ValueError('Expected exactly one Java package declaration')
        # Relocate imported/fully qualified Java type names as well, without
        # rewriting the canonical schema IDs embedded in annotation literals.
        text = re.sub(r'\b' + re.escape(OLD_PACKAGE)
                      + r'(?=\.(?:impl\.|[A-Z]))', NEW_PACKAGE, text)
    else:
        text = re.sub(r'(?m)^(\s*(?:from|import)\s+)' + re.escape(OLD_PACKAGE)
                      + r'(?=\.(?:[a-z_]|impl)|\s|$)',
                      lambda m: m.group(1) + NEW_PACKAGE, text)
        # CHOICE contracts store the generated variant module identities as
        # string literals for lazy imports, not Python import statements.
        # These must follow the relocated bootstrap namespace as well, while
        # the canonical schema IDs in annotation strings remain unchanged.
        text = re.sub(r'(?m)^([ \t]*__xml_choice_variant_imports__\s*=\s*)([^\n]*)$',
                      lambda m: m.group(1) + m.group(2).replace(
                          OLD_PACKAGE + '.', NEW_PACKAGE + '.'), text)
    return text


def collect_existing() -> dict[str, str]:
    """Record current *.extgen sources with repository-relative paths."""
    result = {}
    for _, _, root in OUTPUTS:
        for path in sorted(root.rglob('*')) if root.is_dir() else ():
            if path.is_file() and path.suffix in ('.py', '.java'):
                result[path.relative_to(ROOT).as_posix()] = digest(path.read_bytes())
    return result


def ensure_symmetry(files: dict[str, str],
                    content: dict[str, str] | None = None) -> dict[str, tuple[int, int]]:
    """Validate Defs/SDO schema identity parity between technologies.

    Avoid depending on number of types or the selected naming prefix: the
    canonical model can grow while remaining fully symmetric.
    """
    counts = {}
    identities = {}
    for language, suffix in (('java', '.java'), ('python', '.py')):
        read_root = 'generators/code/defscodegen/intf/src/product/' + language + '.extgen/'
        sdo_root = 'generators/code/defscodegen/impl/src/product/' + language + '.extgen/'
        read = sorted(p for p in files if p.startswith(read_root) and p.endswith(suffix))
        sdo = sorted(p for p in files if p.startswith(sdo_root) and p.endswith(suffix))
        counts[language] = (len(read), len(sdo))
        if not read or not sdo:
            raise RuntimeError('Missing ' + language + ' Defs or SDO extgen sources')
        pattern = (r'schemaId\s*=\s*"([^"]+)"' if language == 'java'
                   else r"schema_id\s*=\s*'([^']+)'")
        groups = {'read': [], 'mutable': [], 'concrete': []}
        for path in read + sdo:
            text = (content[path] if content is not None
                    else (ROOT / path).read_text(encoding='utf-8'))
            match = re.search(pattern, text)
            if not match:
                # Technology-neutral SDO contracts intentionally have no JSON
                # schema identity. Their type names and Java/Python parity are
                # checked separately by validate_sdo_roles().
                if path in sdo and ('/AIigd_j' in path or '/AIcgd_j' in path
                                    or '/aiigd__j_' in path or '/aicgd__j_' in path):
                    raise RuntimeError('Missing JSON SDO identity: ' + path)
                continue
            role = ('read' if path in read else
                    'mutable' if '/impl/intf/' in path else 'concrete')
            groups[role].append(match.group(1))
        valid = set(groups['read'])
        if not valid or len(groups['read']) != len(valid):
            raise RuntimeError('Missing or duplicate Defs IDs for ' + language)
        for role in ('mutable', 'concrete'):
            if set(groups[role]) != valid or len(groups[role]) != len(valid):
                raise RuntimeError('Inconsistent ' + language + ' ' + role + ' schema identities')
        identities[language] = valid
    if counts['java'] != counts['python'] or identities['java'] != identities['python']:
        raise RuntimeError('Java/Python canonical bootstrap differs: ' + repr(counts))
    return counts


def validate_read_roles(files: dict[str, str],
                        content: dict[str, str] | None = None) -> None:
    """Reject format-specific bootstrap read contracts masquerading as common.

    The Defs first stage publishes both technology-neutral AIig... contracts and
    JSON AIig_j... contracts. SDO must select each input's naming convention
    from its annotation/marker, not accept a common name with JSON inheritance.
    Verify the *persistent* input, not just the disposable *.gen sources.
    """
    for name in sorted(files):
        if not (name.startswith('generators/code/defscodegen/intf/src/product/java.extgen/')
                or name.startswith('generators/code/defscodegen/intf/src/product/python.extgen/')):
            continue
        source = (content[name] if content is not None
                  else (ROOT / name).read_text(encoding='utf-8'))
        if name.endswith('.java'):
            kind = re.search(r'\bpublic interface (AIig(?:_j)?[A-Za-z0-9_]+)\b', source)
            if not kind:
                continue  # Enums are not DataObject contracts.
            symbol = kind.group(1)
            if ('@eu.algites.lib.data.dataobject.AIaDataObject(' not in source
                    and '@eu.algites.lib.data.dataobject.jsondefs.AIaJsonDataObject(' not in source):
                continue  # Union/choice marker, not an annotated DataObject contract.
            common = not symbol.startswith('AIig_j')
            json_base = 'eu.algites.lib.data.dataobject.jsondefs.AIiJsonDataObject'
            neutral_base = 'eu.algites.lib.data.dataobject.AIiDataObject'
            json_metadata = 'eu.algites.lib.data.dataobject.jsondefs.AIaJsonDataObject'
            if common and (json_base in source or json_metadata in source
                           or neutral_base not in source):
                raise RuntimeError('Invalid common bootstrap Java Defs contract: ' + name
                                   + ' (' + symbol + ' must be technology-neutral)')
            if not common and (json_base not in source or json_metadata not in source):
                raise RuntimeError('Invalid JSON bootstrap Java Defs contract: ' + name
                                   + ' (' + symbol + ' requires JSON marker/metadata)')
        elif name.endswith('.py'):
            kind = re.search(r'(?m)^class (AIig(?:_j)?[A-Za-z0-9_]+)\(', source)
            if not kind:
                continue
            symbol = kind.group(1)
            if '__data_object__' not in source and '__json_data_object__' not in source:
                continue  # Union/choice marker, not an annotated DataObject contract.
            common = not symbol.startswith('AIig_j')
            class_header = source[kind.start():source.find('\n', kind.start())]
            json_base = 'AIiJsonDataObject' in class_header
            neutral_base = 'AIiDataObject' in class_header
            if common and (json_base or '__json_data_object__' in source
                           or not neutral_base):
                raise RuntimeError('Invalid common bootstrap Python Defs contract: ' + name
                                   + ' (' + symbol + ' must be technology-neutral)')
            if not common and (not json_base or '__json_data_object__' not in source):
                raise RuntimeError('Invalid JSON bootstrap Python Defs contract: ' + name
                                   + ' (' + symbol + ' requires JSON marker/metadata)')



def validate_sdo_roles(files: dict[str, str],
                       content: dict[str, str] | None = None) -> None:
    """Check the *actual* immutable-to-mutable canonical type hierarchy.

    JSON SDO interfaces must extend both their JSON read-only counterpart and
    their corresponding common SDO interface. This catches the stale mixed
    Defs/SDO *.extgen snapshot that caused the Python choice-value TypeError,
    even when somebody regenerated the provenance hashes from the bad sources.
    """
    for language, suffix, read_prefix, mutable_prefix, concrete_prefix, json_marker in (
            ('java', '.java', 'AIig', 'AIigd', 'AIcgd', '_j'),
            ('python', '.py', 'aiig', 'aiigd', 'aicgd', '__j_')):
        read_root = 'generators/code/defscodegen/intf/src/product/' + language + '.extgen/'
        sdo_root = 'generators/code/defscodegen/impl/src/product/' + language + '.extgen/'
        read = {Path(p).name: p for p in files if p.startswith(read_root) and p.endswith(suffix)}
        mutable = {Path(p).name: p for p in files if p.startswith(sdo_root)
                   and '/impl/intf/' in p and p.endswith(suffix)}
        concrete = {Path(p).name: p for p in files if p.startswith(sdo_root)
                    and '/impl/intf/' not in p and p.endswith(suffix)}
        if not mutable or len(mutable) != len(concrete):
            raise RuntimeError('Incomplete ' + language + ' canonical SDO source pairs')

        for filename, path in mutable.items():
            if not filename.startswith(mutable_prefix):
                raise RuntimeError('Unexpected canonical SDO contract: ' + path)
            remainder = filename[len(mutable_prefix):]
            expected_read_filename = read_prefix + remainder
            source_path = read.get(expected_read_filename)
            if source_path is None:
                raise RuntimeError('Missing read-only counterpart for ' + path
                                   + ': ' + expected_read_filename)
            is_json = remainder.startswith(json_marker)
            own_symbol = filename[:-len(suffix)]
            read_symbol = expected_read_filename[:-len(suffix)]
            mutable_text = (content[path] if content is not None
                            else (ROOT / path).read_text(encoding='utf-8'))
            source_text = (content[source_path] if content is not None
                           else (ROOT / source_path).read_text(encoding='utf-8'))
            if language == 'java':
                match = re.search(r'\bpublic interface ' + re.escape(own_symbol)
                                  + r'(?:<[^\n]*?>)?\s+extends ([^\n]+)', mutable_text)
                header = match.group(1) if match else ''
                declared = ('@eu.algites.lib.data.dataobject.AIaDataObject(' in source_text
                            or '@eu.algites.lib.data.dataobject.jsondefs.AIaJsonDataObject(' in source_text)
                json_base = 'eu.algites.lib.data.smartdataobject.jsondefs.AIiJsonSmartDataObject'
            else:
                # Python filenames are snake_case while the generated symbols
                # themselves are CamelCase (e.g. aiigd__j_type_1.py versus
                # AIigd_jType_1). Never treat the filename as the type name.
                own = re.search(r'(?m)^class (AIigd[A-Za-z0-9_]+)\(', mutable_text)
                target = re.search(r'(?m)^class (AIig[A-Za-z0-9_]+)\(', source_text)
                own_symbol = own.group(1) if own else ''
                read_symbol = target.group(1) if target else ''
                match = re.search(r'(?m)^class ' + re.escape(own_symbol)
                                  + r'\(([^\n]+)\):', mutable_text) if own_symbol else None
                header = match.group(1) if match else ''
                declared = ('__data_object__' in source_text
                            or '__json_data_object__' in source_text)
                json_base = 'AIiJsonSmartDataObject'
            if not declared or not re.search(r'\b' + re.escape(read_symbol) + r'\b', header):
                raise RuntimeError('SDO read-only hierarchy mismatch: ' + path
                                   + ' (expected ' + read_symbol + ')')
            if is_json:
                common_remainder = remainder[len(json_marker):]
                if language == 'java':
                    neutral_filename = mutable_prefix + common_remainder
                else:
                    neutral_filename = mutable_prefix + '_' + common_remainder
                common = neutral_filename
                # Synthetic JSON choice branches can be independent of their
                # neutral namesake. Require the common writable parent only
                # when the read-only JSON type inherits the common read type.
                if language == 'java':
                    neutral_read_symbol = read_prefix + common_remainder[:-len(suffix)]
                    neutral_mutable_symbol = common[:-len(suffix)]
                else:
                    neutral_source_filename = read_prefix + '_' + common_remainder
                    neutral_source_path = read.get(neutral_source_filename)
                    neutral_source_text = ((content[neutral_source_path] if content is not None
                                            else (ROOT / neutral_source_path).read_text(encoding='utf-8'))
                                           if neutral_source_path else '')
                    neutral_match = re.search(r'(?m)^class (AIig[A-Za-z0-9_]+)\(', neutral_source_text)
                    neutral_read_symbol = neutral_match.group(1) if neutral_match else ''
                    neutral_mutable_path = mutable.get(common)
                    neutral_mutable_text = ((content[neutral_mutable_path] if content is not None
                                             else (ROOT / neutral_mutable_path).read_text(encoding='utf-8'))
                                            if neutral_mutable_path else '')
                    neutral_match = re.search(r'(?m)^class (AIigd[A-Za-z0-9_]+)\(', neutral_mutable_text)
                    neutral_mutable_symbol = neutral_match.group(1) if neutral_match else ''
                neutral_parent_required = bool(neutral_read_symbol and re.search(
                    r'\b' + re.escape(neutral_read_symbol) + r'\b',
                    source_text[source_text.find('class ' if language == 'python' else 'public interface '):].splitlines()[0]))
                if neutral_parent_required and (common not in mutable or not
                        re.search(r'\b' + re.escape(neutral_mutable_symbol) + r'\b', header)):
                    raise RuntimeError('Missing neutral SDO parent: ' + path
                                       + ' (expected ' + common + ')')
                if json_base not in header:
                    raise RuntimeError('Missing JSON SDO marker: ' + path)
            elif json_base in header:
                raise RuntimeError('Technology-neutral SDO extends JSON: ' + path)

            concrete_name = concrete_prefix + remainder
            concrete_path = concrete.get(concrete_name)
            if concrete_path is None:
                raise RuntimeError('Missing SDO implementation for ' + path)
            concrete_text = (content[concrete_path] if content is not None
                             else (ROOT / concrete_path).read_text(encoding='utf-8'))
            if not re.search(r'\b' + re.escape(own_symbol) + r'\b', concrete_text):
                raise RuntimeError('SDO implementation ignores its interface: ' + concrete_path)

        if len(mutable) != len(concrete) or len(mutable) != sum(
                Path(p).name.startswith(read_prefix)
                and (any(marker in (content[p] if content is not None else (ROOT / p).read_text(encoding='utf-8'))
                         for marker in ('@eu.algites.lib.data.dataobject.AIaDataObject(',
                                        '@eu.algites.lib.data.dataobject.jsondefs.AIaJsonDataObject('))
                     if language == 'java' else
                     any(marker in (content[p] if content is not None else (ROOT / p).read_text(encoding='utf-8'))
                         for marker in ('__data_object__', '__json_data_object__')))
                for p in read.values()):
            raise RuntimeError('Missing SDO coverage of ' + language + ' canonical read contracts')


def refresh_defs() -> None:
    """Promote Defs-only sources; keep the independently generated SDO seed.

    This is the explicit recovery operation when the committed first-stage Defs
    snapshot was generated using the wrong input naming role. It never rewrites
    an SDO source or changes the ordinary bootstrap/prepare operation.
    """
    if not SCHEMA.is_file():
        raise FileNotFoundError(SCHEMA)
    current = collect_existing()
    read: dict[str, str] = {}
    for language, source_root, output in OUTPUTS[:2]:
        source = source_root / OLD_PATH
        suffix = '.java' if language == 'java' else '.py'
        files = sorted(f for f in source.rglob('*') if f.is_file() and f.suffix == suffix)
        if not files:
            raise RuntimeError('Missing generated ' + language + ' Defs contracts: ' + str(source))
        for file in files:
            target = output / NEW_PATH / file.relative_to(source)
            relative = target.relative_to(ROOT).as_posix()
            read[relative] = relocate(NORMALIZE(file.read_text(encoding='utf-8'), language), language)
    # Build a complete prospective snapshot including the unchanged SDO seeds.
    output_roots = [out.relative_to(ROOT).as_posix() + '/' for _, _, out in OUTPUTS[:2]]
    seed = {name: (ROOT / name).read_text(encoding='utf-8') for name in current
            if not any(name.startswith(root) for root in output_roots)}
    if not seed:
        raise RuntimeError('Missing independent SDO bootstrap seed; cannot refresh Defs alone')
    result = {name: digest(text.encode('utf-8')) for name, text in {**seed, **read}.items()}
    validate_read_roles(result, {**seed, **read})
    counts = ensure_symmetry(result, {**seed, **read})
    validate_sdo_roles(result, {**seed, **read})
    # We validated all source roles and Java/Python identities before touching
    # the existing persistent first-stage source roots.
    for _, _, output in OUTPUTS[:2]:
        dest = output / NEW_PATH
        if dest.exists():
            shutil.rmtree(dest)
    for name, text in sorted(read.items()):
        dest = ROOT / name
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(text, encoding='utf-8')
    MANIFEST.write_text(json.dumps({
        'description': ('Schema-generated first-stage canonical model; Defs source roles '
                        'rebuilt independently, SDO seed preserved without modification'),
        'canonical_schema_sha256': digest(SCHEMA.read_bytes()),
        'files': dict(sorted(result.items())),
    }, indent=2) + '\n', encoding='utf-8')
    print(f'Promoted read-only bootstrap contracts, retained independent SDO seed: '
          f'{len(result)} files (Java={sum(counts["java"])}, '
          f'Python={sum(counts["python"])}; '
          f'read={counts["java"][0]}, SDO={counts["java"][1]} per language)')


def check() -> None:
    """Ensure committed extgen output and generating schema are unchanged."""
    if not MANIFEST.is_file():
        raise RuntimeError('Missing canonical bootstrap provenance manifest')
    expected = json.loads(MANIFEST.read_text(encoding='utf-8'))
    if expected['canonical_schema_sha256'] != digest(SCHEMA.read_bytes()):
        raise RuntimeError('Canonical schema changed; refresh generated bootstrap extgen')
    files = collect_existing()
    if files != expected['files']:
        missing = sorted(set(expected['files']) - set(files))
        extra = sorted(set(files) - set(expected['files']))
        changed = sorted(k for k in files.keys() & expected['files'].keys()
                         if files[k] != expected['files'][k])
        raise RuntimeError(f'Bootstrap extgen stale (missing={missing}, extra={extra}, changed={changed})')
    validate_read_roles(files)
    counts = ensure_symmetry(files)
    validate_sdo_roles(files)
    print(f'Canonical bootstrap *.extgen verified: {len(files)} generated files '
          f'(Java={sum(counts["java"])}, Python={sum(counts["python"])}; '
          f'read={counts["java"][0]}, SDO={counts["java"][1]} per technology)')


def prune_seed() -> None:
    """Discard historical *.extgen source paths, without comparing old hashes.

    An extracted source archive can overlay obsolete generated files. The
    current provenance manifest defines which *paths* belong to this version's
    bootstrap seed; it does not veto changed contents. The successful full
    bootstrap will replace all four seed trees from its fresh *.gen outputs.
    """
    if not MANIFEST.is_file():
        raise RuntimeError('Missing canonical bootstrap seed manifest: ' + str(MANIFEST))
    snapshot = json.loads(MANIFEST.read_text(encoding='utf-8'))
    expected = snapshot.get('files')
    if not isinstance(expected, dict) or not expected:
        raise RuntimeError('Invalid canonical bootstrap seed file list')
    prefixes = tuple(output.relative_to(ROOT).as_posix() + '/' for _, _, output in OUTPUTS)
    if any(not name.startswith(prefixes) or Path(name).is_absolute()
           or '..' in Path(name).parts for name in expected):
        raise RuntimeError('Canonical bootstrap seed contains an unsafe path')
    removed = 0
    for _, _, output in OUTPUTS:
        if output.is_symlink():
            raise RuntimeError('Refusing symlinked bootstrap seed: ' + str(output))
        if not output.is_dir():
            raise RuntimeError('Missing bootstrap seed directory: ' + str(output))
        for entry in output.rglob('*'):
            if entry.is_symlink():
                raise RuntimeError('Refusing symlinked bootstrap seed entry: ' + str(entry))
        for entry in sorted(output.rglob('*'), reverse=True):
            if entry.is_file() and entry.suffix in {'.java', '.py'}:
                if entry.relative_to(ROOT).as_posix() not in expected:
                    entry.unlink()
                    removed += 1
            elif entry.is_dir() and not any(entry.iterdir()):
                entry.rmdir()
    print(f'Bootstrap seed prepared: {removed} historical extra files removed; '
          'no hash comparison against previous runs')


def refresh() -> None:
    """Atomically promote the four freshly generated Defs/SDO source sets.

    Validate the complete new snapshot *before* touching any existing seed;
    stage all four trees and the manifest, then exchange them with rollback.
    A failure must not leave half the bootstrap model refreshed. Each stage
    uses the same parent filesystem as its destination for safe renames.
    """
    if not SCHEMA.is_file():
        raise FileNotFoundError(SCHEMA)
    sources: dict[str, str] = {}
    for language, source_root, output in OUTPUTS:
        source = source_root / OLD_PATH
        suffix = '.java' if language == 'java' else '.py'
        files = (sorted(path for path in source.rglob('*') if path.suffix == suffix)
                 if source.is_dir() else [])
        if not files:
            raise RuntimeError('Missing freshly generated canonical ' + language + ' contracts: '
                               + str(source))
        if output.is_symlink():
            raise RuntimeError('Refusing symlinked bootstrap destination: ' + str(output))
        for file in files:
            if file.is_symlink():
                raise RuntimeError('Refusing symlinked generated canonical source: ' + str(file))
            target = output / NEW_PATH / file.relative_to(source)
            relative = target.relative_to(ROOT).as_posix()
            if relative in sources:
                raise RuntimeError('Duplicate generated canonical source: ' + relative)
            sources[relative] = relocate(NORMALIZE(file.read_text(encoding='utf-8'), language), language)
    result = {name: digest(value.encode('utf-8')) for name, value in sources.items()}
    validate_read_roles(result, sources)
    counts = ensure_symmetry(result, sources)
    validate_sdo_roles(result, sources)

    manifest_text = json.dumps({
        'description': ('Schema-generated first-stage canonical model; independent '
                        'Defs read-only and SDO writable/implementation outputs, '
                        'both technologies, never handwritten'),
        'canonical_schema_sha256': digest(SCHEMA.read_bytes()),
        'files': dict(sorted(result.items())),
    }, indent=2) + '\n'
    token = uuid.uuid4().hex
    staged: list[tuple[Path, Path, Path]] = []
    manifest_stage = MANIFEST.with_name(MANIFEST.name + '.stage-' + token)
    completed: list[tuple[Path, Path, bool]] = []
    success = False
    try:
        for _, _, output in OUTPUTS:
            output.parent.mkdir(parents=True, exist_ok=True)
            stage = output.with_name(output.name + '.stage-' + token)
            backup = output.with_name(output.name + '.backup-' + token)
            stage.mkdir(mode=0o700)
            staged.append((output, stage, backup))
        roots = {output.relative_to(ROOT).as_posix() + '/': stage
                 for output, stage, _ in staged}
        for name, value in sorted(sources.items()):
            prefix = next((prefix for prefix in roots if name.startswith(prefix)), None)
            if prefix is None:
                raise RuntimeError('Unowned bootstrap output: ' + name)
            target = roots[prefix] / name[len(prefix):]
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(value, encoding='utf-8')
        manifest_stage.write_text(manifest_text, encoding='utf-8')

        for output, stage, backup in staged:
            existed = output.exists()
            if existed:
                os.replace(output, backup)
            try:
                os.replace(stage, output)
            except BaseException:
                if existed:
                    os.replace(backup, output)
                raise
            completed.append((output, backup, existed))
        # Only the last atomic rename publishes the matching new manifest.
        os.replace(manifest_stage, MANIFEST)
        success = True
    except BaseException:
        for output, backup, existed in reversed(completed):
            if output.exists():
                shutil.rmtree(output)
            if existed:
                os.replace(backup, output)
        raise
    finally:
        for _, stage, backup in staged:
            if stage.exists():
                shutil.rmtree(stage)
            if success and backup.exists():
                shutil.rmtree(backup)
        manifest_stage.unlink(missing_ok=True)
    print(f'Promoted {len(result)} generated contracts into persistent *.extgen roots '
          f'(Java={sum(counts["java"])}, Python={sum(counts["python"])}; '
          f'read={counts["java"][0]}, SDO={counts["java"][1]} per technology)')

def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--refresh', action='store_true', help='Regenerate persistent snapshot from *.gen outputs')
    group.add_argument('--refresh-defs', action='store_true',
                       help='Update only read contracts, keeping existing generated SDO seed')
    group.add_argument('--check', action='store_true', help='Explicit check of committed snapshot')
    group.add_argument('--prune-seed', action='store_true', help='Remove historical extra seed files without comparing hashes')
    args = parser.parse_args()
    if args.refresh:
        refresh()
    elif args.refresh_defs:
        refresh_defs()
    elif args.prune_seed:
        prune_seed()
    else:
        check()


if __name__ == '__main__':
    main()
