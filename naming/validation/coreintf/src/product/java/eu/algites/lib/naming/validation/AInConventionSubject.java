package eu.algites.lib.naming.validation;

/** Governed convention subjects supported by the generic checker. */
public enum AInConventionSubject {
    /** Represents the definition name value. */
    DEFINITION_NAME,
    /** Represents the property name value. */
    PROPERTY_NAME,
    /** Represents the enum value value. */
    ENUM_VALUE,
    /** Represents the symbolic map key value. */
    SYMBOLIC_MAP_KEY,
    /** Represents the package segment value. */
    PACKAGE_SEGMENT,
    /** Represents the input version value. */
    INPUT_VERSION,
    /** Represents the output version value. */
    OUTPUT_VERSION
}
