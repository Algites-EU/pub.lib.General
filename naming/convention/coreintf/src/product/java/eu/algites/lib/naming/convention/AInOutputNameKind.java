package eu.algites.lib.naming.convention;

/** Semantic categories of generated program names. */
public enum AInOutputNameKind {
    /** Represents the data type value. */
    DATA_TYPE,
    /** Represents the enum type value. */
    ENUM_TYPE,
    /** Represents the interface type value. */
    INTERFACE_TYPE,
    /** Represents the property value. */
    PROPERTY,
    /** Represents the enum constant value. */
    ENUM_CONSTANT,
    /** Represents the package segment value. */
    PACKAGE_SEGMENT,
    /** Represents the file stem value. */
    FILE_STEM,
    /** Represents the data type file stem value. */
    DATA_TYPE_FILE_STEM,
    /** Represents the enum type file stem value. */
    ENUM_TYPE_FILE_STEM,
    /** Represents the interface type file stem value. */
    INTERFACE_TYPE_FILE_STEM
}
