package eu.algites.lib.naming.convention;

/** Supported word-boundary and case conventions. */
public enum AInNameConvention {
    /** Represents the as is value. */
    AS_IS,
    /** Represents the lower snake case value. */
    LOWER_SNAKE_CASE,
    /** Represents the upper snake case value. */
    UPPER_SNAKE_CASE,
    /** Represents the lower camel case value. */
    LOWER_CAMEL_CASE,
    /** Represents the upper camel case value. */
    UPPER_CAMEL_CASE,
    /** Represents the lower kebab case value. */
    LOWER_KEBAB_CASE,
    /** Represents the upper kebab case value. */
    UPPER_KEBAB_CASE
}
